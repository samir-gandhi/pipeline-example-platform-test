#!/usr/bin/env sh
# Export supported PingOne/DaVinci configuration for the current feature branch.

set -eu

_usage() {
  printf '%s\n' "Usage: $0 [--environment-id UUID] [--out DIR]"
  exit 2
}

_environment_id=""
_output_dir="terraform"
_repo_root=$(git rev-parse --show-toplevel)
cd "${_repo_root}"

while [ "$#" -gt 0 ]; do
  case "$1" in
    --environment-id)
      [ "$#" -ge 2 ] || _usage
      _environment_id="$2"
      shift 2
      ;;
    --out)
      [ "$#" -ge 2 ] || _usage
      _output_dir="$2"
      shift 2
      ;;
    -h|--help)
      _usage
      ;;
    *)
      _usage
      ;;
  esac
done

command -v pingcli-terraformer >/dev/null 2>&1 || {
  printf '%s\n' "pingcli-terraformer is required; install pingidentity/pingcli-plugin-terraformer first." >&2
  exit 1
}
command -v terraform >/dev/null 2>&1 || {
  printf '%s\n' "terraform is required." >&2
  exit 1
}

# The Terraformer worker credentials default to the same worker app that
# drives Terraform (sourced from localsecrets as TF_VAR_pingone_client_*).
# Dedicated PINGCLI_PINGONE_* values still win if exported.
: "${PINGCLI_PINGONE_CLIENT_CREDENTIALS_CLIENT_ID:=${TF_VAR_pingone_client_id-}}"
: "${PINGCLI_PINGONE_CLIENT_CREDENTIALS_CLIENT_SECRET:=${TF_VAR_pingone_client_secret-}}"
: "${PINGCLI_PINGONE_ENVIRONMENT_ID:=${TF_VAR_pingone_client_environment_id-}}"
: "${PINGCLI_PINGONE_REGION_CODE:=${TF_VAR_pingone_client_region_code-}}"

[ -n "${PINGCLI_PINGONE_CLIENT_CREDENTIALS_CLIENT_ID-}" ] || {
  printf '%s\n' "PINGCLI_PINGONE_CLIENT_CREDENTIALS_CLIENT_ID is required." >&2
  exit 1
}
[ -n "${PINGCLI_PINGONE_CLIENT_CREDENTIALS_CLIENT_SECRET-}" ] || {
  printf '%s\n' "PINGCLI_PINGONE_CLIENT_CREDENTIALS_CLIENT_SECRET is required." >&2
  exit 1
}
[ -n "${PINGCLI_PINGONE_ENVIRONMENT_ID-}" ] || {
  printf '%s\n' "PINGCLI_PINGONE_ENVIRONMENT_ID is required." >&2
  exit 1
}
[ -n "${PINGCLI_PINGONE_REGION_CODE-}" ] || {
  printf '%s\n' "PINGCLI_PINGONE_REGION_CODE is required." >&2
  exit 1
}

_branch=$(git rev-parse --abbrev-ref HEAD)
case "${_branch}" in
  ''|HEAD|*[!A-Za-z0-9._/-]*)
    printf '%s\n' "A named branch is required; use --environment-id from a detached checkout." >&2
    exit 1
    ;;
esac

if [ -z "${_environment_id}" ]; then
  if [ -f localsecrets ]; then
    # Use the same remote state key as the deployment workflows.
    . ./localsecrets
    case "${_branch}" in
      prod) _state_key="${TF_VAR_tf_state_key_prefix}/prod/terraform.tfstate" ;;
      qa) _state_key="${TF_VAR_tf_state_key_prefix}/qa/terraform.tfstate" ;;
      *) _state_key="${TF_VAR_tf_state_key_prefix}/dev/${_branch}/terraform.tfstate" ;;
    esac
    terraform -chdir=terraform init -input=false -reconfigure \
      -backend-config="bucket=${TF_VAR_tf_state_bucket}" \
      -backend-config="region=${TF_VAR_tf_state_region}" \
      -backend-config="key=${_state_key}" >/dev/null
  fi
  _environment_id=$(terraform -chdir=terraform output -raw pingone_environment_id 2>/dev/null || true)
fi

[ -n "${_environment_id}" ] || {
  printf '%s\n' "Pass --environment-id or initialize the branch Terraform state." >&2
  exit 1
}

case "${_environment_id}" in
  [0-9a-fA-F][0-9a-fA-F]*-[0-9a-fA-F-]*) ;;
  *) printf '%s\n' "Environment ID must be a UUID." >&2; exit 1 ;;
esac

mkdir -p "${_output_dir}"
pingcli-terraformer export \
  --pingone-worker-environment-id "${PINGCLI_PINGONE_ENVIRONMENT_ID}" \
  --pingone-export-environment-id "${_environment_id}" \
  --pingone-worker-client-id "${PINGCLI_PINGONE_CLIENT_CREDENTIALS_CLIENT_ID}" \
  --pingone-worker-client-secret "${PINGCLI_PINGONE_CLIENT_CREDENTIALS_CLIENT_SECRET}" \
  --pingone-region-code "${PINGCLI_PINGONE_REGION_CODE}" \
  --include-values \
  --include-imports \
  --output-attribute 'pingone_davinci_connector_instance.*.id' \
  --output-attribute 'pingone_davinci_flow.*.id' \
  --output-attribute 'pingone_davinci_application_flow_policy.*.id' \
  --output-attribute 'pingone_davinci_application.*.api_key.value' \
  --out "${_output_dir}"

# --- Post-export hooks ------------------------------------------------------
# The exporter rewrites the module directory; hand-maintained additions must be
# restored afterwards. Outputs are generated by the export tool itself via
# --output-attribute. Connector credentials and the environment id are NOT
# exported into tfvars: the module derives them from the environment's worker
# applications and target_environment, so every branch deploys the same code.
# Strip the exporter's variable lines (and the generated imports, which only
# apply to the source environment) if present.
if [ "${_output_dir}" = "terraform" ]; then
  [ -f terraform/ping-export-imports.tf ] && mv terraform/ping-export-imports.tf \
    terraform/imports-reference.tf 2>/dev/null
  # 4. The exporter regenerates the module wrapper with var-based connector
  #    credentials; restore the derived-credential wrapper (protected by a
  #    marker so this hook only rewrites when the exporter clobbered it).
  if [ -f terraform/ping-export-module.tf ] \
      && ! grep -q "DERIVED-CONNECTOR-CREDS" terraform/ping-export-module.tf; then
    cat > terraform/ping-export-module.tf <<'WRAPPER'
# DERIVED-CONNECTOR-CREDS: regenerated by scripts/export_pingone.sh
module "ping-export" {
  source = "./ping-export-module"

  pingone_environment_id = pingone_environment.target_environment.id

  # Connector credentials are derived from the environment's worker
  # applications rather than exported values, so the same code deploys to
  # any environment without per-branch tfvars for these fields.
  davinci_connection_PingOne_0020_Protect_clientId     = pingone_application.protect_worker.id
  davinci_connection_PingOne_0020_Protect_clientSecret = pingone_application_secret.protect_worker_app.secret
  davinci_connection_PingOne_0020_Protect_envId        = pingone_environment.target_environment.id
  davinci_connection_PingOne_0020_Protect_region       = var.pingone_client_region_code
  davinci_connection_PingOne_clientId                  = pingone_application.davinci_connection_worker.id
  davinci_connection_PingOne_clientSecret              = pingone_application_secret.davinci_connection_worker.secret
  davinci_connection_PingOne_envId                     = pingone_environment.target_environment.id
  davinci_connection_PingOne_region                    = var.pingone_client_region_code

}
WRAPPER
  fi
  # 5. Drop the exporter's connector variable blocks from the root variables
  #    file; the wrapper no longer passes them.
  if [ -f terraform/ping-export-variables.tf ] && grep -q "davinci_connection_" terraform/ping-export-variables.tf; then
    python3 - <<'PYSTRIP'
import re
p = 'terraform/ping-export-variables.tf'
t = open(p).read()
t = re.sub(r'# Pingone_davinci_connector_instance Variables\n\n?', '', t)
t = re.sub(r'variable "davinci_connection_[^"]*" \{.*?\n\}\n\n?', '', t, flags=re.S)
open(p, 'w').write(t)
PYSTRIP
  fi
  # 6. Drop the envId line + connector lines from the generated tfvars.
  if [ -f terraform/ping-export-terraform.auto.tfvars ]; then
    sed -i '' -e '/^davinci_connection_/d' -e '/^pingone_environment_id/d' \
      -e '/# Terraform variable values/d' -e '/# Pingone_davinci_connector_instance/d' \
      terraform/ping-export-terraform.auto.tfvars 2>/dev/null || \
    sed -i -e '/^davinci_connection_/d' -e '/^pingone_environment_id/d' \
      -e '/# Terraform variable values/d' -e '/# Pingone_davinci_connector_instance/d' \
      terraform/ping-export-terraform.auto.tfvars
  fi
  # 7. The exporter emits interpolation-only expressions ("${var.x}") inside
  #    jsonencode blocks; tflint flags those as deprecated. Rewrite to plain
  #    references (var.x) — identical behavior, lint-clean.
  find terraform/ping-export-module -name '*.tf' -print0 | xargs -0 perl -pi -e \
    's/"\$\{var\.([A-Za-z0-9_]+)\}"/var.$1/g'
fi

